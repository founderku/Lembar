(function(){
  var BULAN = ['Januari','Februari','Maret','April','Mei','Juni','Juli','Agustus','September','Oktober','November','Desember'];
  var BULAN_SINGKAT = ['Jan','Feb','Mar','Apr','Mei','Jun','Jul','Agu','Sep','Okt','Nov','Des'];

  window.LembarUtil = {
    fmtDateShort: function(iso){
      var d = new Date(iso); if(isNaN(d)) return '';
      return d.getDate()+' '+BULAN_SINGKAT[d.getMonth()]+' '+d.getFullYear();
    },
    fmtDateLong: function(iso){
      var d = new Date(iso); if(isNaN(d)) return '';
      return d.getDate()+' '+BULAN[d.getMonth()]+' '+d.getFullYear();
    },
    escapeHtml: function(s){
      return String(s==null?'':s).replace(/[&<>"']/g, function(c){
        return {'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c];
      });
    },
    excerpt: function(s, n){
      s = String(s||'').replace(/\s+/g,' ').trim();
      if(s.length<=n) return s;
      var cut = s.slice(0,n);
      var lastSpace = cut.lastIndexOf(' ');
      if(lastSpace>40) cut = cut.slice(0,lastSpace);
      return cut+'…';
    },
    slugify: function(s){
      return String(s||'').toLowerCase().trim()
        .normalize('NFKD').replace(/[̀-ͯ]/g,'')
        .replace(/[^a-z0-9]+/g,'-').replace(/^-+|-+$/g,'') || 'penulis';
    },
    initials: function(name){
      var parts = String(name||'?').trim().split(/\s+/).filter(Boolean);
      if(!parts.length) return '?';
      if(parts.length===1) return parts[0].slice(0,2).toUpperCase();
      return (parts[0][0]+parts[parts.length-1][0]).toUpperCase();
    },
    uid: function(){
      return 'k'+Date.now().toString(36)+Math.random().toString(36).slice(2,8);
    },
    toast: function(msg, ok){
      var root = document.getElementById('toast-root');
      if(!root){ root = document.createElement('div'); root.id='toast-root'; document.body.appendChild(root); }
      var el = document.createElement('div');
      el.className = 'toast';
      el.innerHTML = (ok!==false? window.LembarIconsMisc.check : '') + '<span></span>';
      el.querySelector('span').textContent = msg;
      root.appendChild(el);
      setTimeout(function(){ el.style.opacity='0'; el.style.transition='opacity .25s ease'; setTimeout(function(){ el.remove(); }, 260); }, 2600);
    }
  };
})();
